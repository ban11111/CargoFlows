type ExactSameKeys<Left, Right> =
  Exclude<keyof Left, keyof Right> extends never
    ? Exclude<keyof Right, keyof Left> extends never
      ? true
      : never
    : never;

export const messageKeyParity: ExactSameKeys<typeof messages.zh, typeof messages.en> = true;
export type MessageKey = keyof typeof messages.zh;

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  // Keep the server and the first client render identical. Reading localStorage
  // during initialization can otherwise change server-rendered Chinese text to
  // English before hydration, preventing React from attaching form handlers.
  const [language, setLanguageState] = useState<Language>("zh");

  useEffect(() => {
    const saved = window.localStorage.getItem(storageKey);
    if (saved === "zh" || saved === "en") {
      const frame = window.requestAnimationFrame(() => setLanguageState(saved));
      return () => window.cancelAnimationFrame(frame);
    }
  }, []);

  const value = useMemo<LanguageContextValue>(() => {
    return {
      language,
      setLanguage(nextLanguage) {
        setLanguageState(nextLanguage);
        window.localStorage.setItem(storageKey, nextLanguage);
      },
      t(key) {
        return messages[language][key];
      },
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return value;
}
